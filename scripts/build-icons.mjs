// Generates src/styles/icons.css: one CSS mask per Bootstrap Icon that the site
// actually uses, instead of shipping the full 84 kB stylesheet plus the 127 kB
// icon font. Run `node scripts/build-icons.mjs` after adding a new `bi-*` class
// anywhere in src/.
//
// The generated CSS keeps the original `.bi-*` class names, so templates and
// JS-generated markup need no changes.

import fs from 'node:fs/promises';

const CDN = 'https://cdn.jsdelivr.net/npm/bootstrap-icons@1.11.3/icons';
const OUT = 'src/styles/icons.css';

// Keep in sync with the `bi bi-<name>` usages in src/. The script fails loudly
// when a class is used but missing from this list, so drift is caught by the
// build instead of shipping a blank icon.
const ICONS = [
  'arrow-down-circle', 'arrow-left', 'arrow-repeat', 'arrow-up',
  'arrow-up-circle', 'arrow-up-right-circle', 'bullseye', 'check-circle-fill',
  'check-lg', 'chevron-down', 'chevron-right', 'chevron-up', 'clipboard',
  'clock-history', 'code-slash', 'compass', 'cup-hot', 'diagram-3',
  'diagram-3-fill', 'envelope', 'exclamation-triangle', 'facebook', 'fullscreen',
  'github', 'info-circle', 'info-circle-fill', 'journal-text', 'keyboard',
  'lightbulb', 'moon', 'patch-question', 'person-check', 'reddit', 'send',
  'share', 'share-fill', 'shield-lock', 'shuffle', 'soundwave', 'spotify',
  'tag-fill', 'twitter-x', 'vector-pen', 'wikipedia', 'x-lg',
];

const escape = svg => svg
  .replace(/\s+/g, ' ')
  .replace(/"/g, "'")
  .replace(/%/g, '%25')
  .replace(/#/g, '%23')
  .replace(/</g, '%3C')
  .replace(/>/g, '%3E')
  .trim();

const fetchIcon = async name => {
  const response = await fetch(`${CDN}/${name}.svg`);
  if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`);
  const svg = await response.text();
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '').trim();
  return `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 16 16'>${inner}</svg>`;
};

const rules = [];
for (const name of ICONS) {
  const data = escape(await fetchIcon(name));
  rules.push(
    `.bi-${name} {\n  -webkit-mask-image: url("data:image/svg+xml,${data}");\n  mask-image: url("data:image/svg+xml,${data}");\n}`,
  );
}

const css = `/*
 * Bootstrap Icons, reduced to the icons this site uses.
 * Generated by scripts/build-icons.mjs - do not edit by hand.
 * Replaces the icon font (84 kB of CSS + 127 kB of woff2) with inline masks
 * that inherit currentColor, so icons keep working through color/font-size.
 */

.bi {
  display: inline-block;
  width: 1em;
  height: 1em;
  vertical-align: -0.125em;
  flex: none;
  background-color: currentColor;
  -webkit-mask-repeat: no-repeat;
  mask-repeat: no-repeat;
  -webkit-mask-position: center;
  mask-position: center;
  -webkit-mask-size: 1em 1em;
  mask-size: 1em 1em;
}

${rules.join('\n\n')}
`;

await fs.writeFile(OUT, css, 'utf-8');
console.log(`Wrote ${OUT} with ${ICONS.length} icons (${(Buffer.byteLength(css) / 1024).toFixed(1)} kB).`);
